"""预处理子图宏观内容单元发现节点的任务提示词。"""

from __future__ import annotations

from app.agent.contract_extraction.state import PDFPromptPage, PreparedPDFPage
from app.agent.contract_extraction.tool_protocol import TOOL_CALL_XML_INSTRUCTION
from app.agent.contract_extraction.subgraph.preprocessing.prompt import (
    build_pdf_messages,
)

UNIT_DISCOVERY_PROMPT_VERSION = "document-structure-unit-discovery-v11"

UNIT_DISCOVERY_TASK = f"""你已获得按物理页码排列的完整合同 PDF。当前任务是建立一份中等粒度的合同导航结构，供字段、条款和摘要等具体任务准确定位合同内容。

内容单元定义：
内容单元位于“整份合同”和“最小条款”之间，是合同原始顺序中一个连续、功能完整且可以独立导航的内容区域。在同一具体功能内部尽量合并，不同导航功能之间保持分离。

一个完整单元必须：
1. 回答一个可以被独立检索和处理的具体问题；
2. 能够使用具体名称和一段摘要独立描述；
3. 包含理解该功能所必需的标题、正文、表格、备注、例外和跨页延续；
4. 具有可核对的开始与结束边界；
5. 不包含另一个明显独立且需要不同处理方式的主要功能。

“整份合同”“合同主文”“合同主体”“完整页面”“完成交易”属于文档级目的，不能作为内容单元的主导功能。标签不得使用“第X页内容”代替实际功能。

标准结构先验：
多数采购、销售、制造和普通服务合同，优先检查是否存在以下候选功能：
1. 合同首部与当事人：合同名称、编号、日期、地点及当事人基础身份；
2. 交易标的与金额：商品、服务或工程对象，规格、数量、质量、价格、税费及直接属性；
3. 履行与通用条款：付款、交付、工期、验收、质保、双方义务、违约及争议处理；
4. 签署与结算身份信息：签字、盖章、代理人、签署日期，以及与签署区紧密排布的账户和税务身份；
5. 附件与专业资料：报价、清单、技术规格、施工方案、检测项目或设计图纸。

上述结构只是优先检查的先验，不是固定单元数量。实际合同可以缺失、合并、拆分、重排这些功能，也可以出现保险责任、责任免除、保密范围、数据处理、补充变更等新功能。不得为了匹配标准结构而虚构、移动、遗漏或曲解内容。

拆分与合并规则：
1. 相邻区域回答不同的独立问题、各自能够独立命名和理解，并存在可核对的文字或视觉边界时，应当拆分。
2. 法律上共同构成一份合同不等于导航功能相同。主体身份、交易核心、履行风险和签署认证在边界清楚时应保持分离。
3. 内容共同回答同一个具体问题，或者后一部分只是前一部分的标题、补充、例外、备注或跨页延续时，应当合并。
4. 表头、表格行、合计、税费说明和与标的直接相关的短说明应保持完整；主条款与紧随其后的例外或补充说明应保持完整。
5. 不得仅因条款编号、自然段、换页、续表、页眉页脚或短小备注而切分。
6. 正文与附件、不同用途的附件、不同专业的图纸可以分别形成单元；同一附件或同一专业下连续且用途相同的页面应当合并。
7. 简短紧凑的履行、风险和争议条款可以合为“履行与通用条款”；长篇条款内部若出现可独立检索且边界明确的保险责任、责任免除、赔偿处理等宏观功能，可以继续拆分。

少样本粒度校准：
以下示例提取自测试合同，只展示经典切分结构，不提供可复用的主体、金额或字段答案。不得把示例内容复制到当前合同。

示例一：单页标准买卖合同。
- 单元1“合同首部与当事人”：从合同标题开始，到双方基础联系方式结束；
- 单元2“交易标的与金额”：从订购说明和产品表开始，到总金额、税费及与标的直接相关的制造商说明结束；
- 单元3“履行与通用条款”：从交货或付款条款开始，到违约、合同效力和争议解决条款结束；
- 单元4“签署与结算身份信息”：从双方签署栏开始，到签章、代理人、账户及税号区域结束。
不得把整页命名为“买卖合同完整页面”，也不得把付款、包装、运输、质保和仲裁逐条拆成单元。

示例二：多页设备合同及技术附件。
- 单元1“合同首部与当事人”：合同标题与双方身份页；
- 单元2“交易标的与金额”：产品规格、数量、价格和税费表所在区域；
- 单元3“履行与权利义务条款”：从同页后半部分开始并跨页延续的交货、质保、付款和通用法律条款；
- 单元4“签署与附件声明”：合同效力、附件清单和双方签章区域；
- 单元5“技术图纸附件”：独立的设备尺寸和结构图纸。
换页没有切断同一履行功能；正文、签署区和技术图纸因用途及版式不同而保持分离。

执行规则：
1. 首轮必须调用 summary，按照 evidence、reasoning_summary、decision 的顺序总结整份合同讨论的内容。
2. summary 成功后的第一次操作必须调用 think，先识别主合同、附件、报价、清单、方案或图纸等文档组成，再将实际内容与标准结构先验逐项比较，列出候选单元、边界证据及所有偏离理由。
3. 此后继续使用 think、generate_unit 或 finish；每轮必须且只能调用一个工具。think 只记录简洁的自然语言理由，不输出冗长草稿。
4. generate_unit 每次只提交一个宏观、连续的内容单元，并按照 evidence、reasoning_summary、decision 的顺序提供参数。
5. 每个单元的 evidence 应优先提供主题证据和起止边界证据；只保留足以核对判断的短片段，单条通常不超过 120 个汉字，不得复制整页、整段条款或完整主体联系方式。
6. 每个单元的 reasoning_summary 必须说明它回答哪个独立问题、内部内容为何应合并、为何不应与前后单元合并、起止位置为何是真实边界，以及是否偏离标准结构。最终决定不得引入证据和推理摘要未支持的事实。
7. 当前任务只发现语义单元，不生成坐标。start 与 end 使用物理页码、可核对的文本或视觉锚点及 inclusion 定义权威连续边界；坐标定位会在获得这些边界后单独完成。
8. 每个 span 都必须提交 navigation_anchors；普通单页单元通常传空列表。仅当跨页延续、双栏换栏或复杂版式确实需要帮助沿阅读顺序定位时，才添加少量中间锚点。锚点按物理页码和页内阅读顺序排列，不得重复 start、end，不得把每条条款或自然段都变成锚点。
9. 按合同原始顺序生成单元。存在遮挡、缺页、边界不清或多种合理切法时，在 evidence 与 reasoning_summary 中明确说明不确定性；不得虚构页面或锚点。中间页面没有可靠锚点时保留为空，程序可以补充 page_body 锚点。
10. 所有候选内容生成后，调用 finish 之前必须先调用一次 think，检查是否把单页合同错误合成一个单元、是否按编号条款过度切分、标准结构中实际存在的功能是否被其他单元吞并、是否存在孤立标题、备注、续表、签章或附件，以及模板外内容是否被强行归类。发现问题时不得直接 finish。
11. 只有确认所有页面中的宏观内容都已经被合理单元覆盖后才能调用 finish。
12. 工具返回 ok=false 时，严格按照 message 指出的错误位置、问题和改进方向修正下一次调用。

工具调用格式：
{TOOL_CALL_XML_INSTRUCTION}
"""


def build_unit_discovery_messages(
    pages: tuple[PreparedPDFPage, ...],
    prompt_pages: tuple[PDFPromptPage, ...],
) -> list[dict[str, object]]:
    """复用 PDF 公共前缀，并把结构发现任务稳定追加在页面之后。"""
    return build_pdf_messages(
        pages,
        prompt_pages,
        task_suffix=UNIT_DISCOVERY_TASK,
    )
