def prepare_file_text_summaries(file_summaries: Sequence[FileSummary]) -> tuple[FileSummary, ...]:
    """确认完整的本轮上传序列，禁止静默漏项后伪造第一份或最后一份。"""
    files = tuple(sorted((FileSummary.model_validate(f) for f in file_summaries), key=lambda f: f.file_index))
    if not files or [f.file_index for f in files] != list(range(len(files))):
        raise ValueError('必须提供从 0 开始连续且唯一的全部文件摘要')
    return files


def build_file_text_relevance_messages(*, text: str, file_summaries: Sequence[FileSummary]) -> list[dict[str, str]]:
    """两个明确区域；原始名辅助指代，不注入字节、路径、UUID、历史或审计。"""
    if not isinstance(text, str) or not text.strip():
        raise ValueError('text 必须是非空字符串')
    files = prepare_file_text_summaries(file_summaries)
    # 每个区域独立 YAML 序列化，多行输入不能注入新的顶层区域。
    text_yaml = yaml.safe_dump({'text': text}, allow_unicode=True, sort_keys=False, width=1000)
    files_yaml = yaml.safe_dump({'files': [
        {'upload_order': f.file_index + 1, 'original_file_name': f.original_file_name,
         'display_name': f.display_name, 'summary': f.summary} for f in files
    ]}, allow_unicode=True, sort_keys=False, width=1000)
    return [
        {'role': 'system', 'content': FILE_TEXT_RELEVANCE_SYSTEM_PROMPT
         + '\n\n## 输出 JSON Schema\n\n'
         + json.dumps(FileTextRelevanceGeneration.model_json_schema(), ensure_ascii=False, separators=(',', ':'))},
        {'role': 'user', 'content': '## 文字区\n\n' + text_yaml + '\n---\n\n## 文件摘要区\n\n' + files_yaml},
    ]
