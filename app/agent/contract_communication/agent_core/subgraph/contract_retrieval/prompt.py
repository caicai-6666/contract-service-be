def render_business_definitions(field_catalog, category_catalog) -> str:
    """供业务对齐节点使用，投影语义与硬约束，不泄漏索引配置、目录路径或专家样例。"""
    import yaml

    def block(value):
        return '```yaml\n' + yaml.safe_dump(value, allow_unicode=True, sort_keys=False, width=100).strip() + '\n```'

    sections = ['# Core 字段定义',
        '字段和属性的 code 是稳定引用；枚举的 value 是标准值，label 是展示名称。数值范围和倍数属于硬约束。']
    for definition in field_catalog.core.definitions:
        props = []
        for prop in definition.properties:
            item = {'属性名称': prop.name, 'property_code': prop.code, '值类型': prop.type.value,
                    '含义': prop.meaning.strip(), '排除': prop.excludes.strip(),
                    '提取与转换': prop.extraction_rule}
            if prop.aliases:
                item['别名'] = list(prop.aliases)
            constraints = prop.constraints.model_dump(mode='json', exclude_none=True)
            if constraints:
                item['允许值与范围'] = constraints
            props.append(item)
        sections.extend([f'## {definition.name}（{definition.code}）', block({
            'code':definition.code, '别名':list(definition.aliases),
            '含义':definition.meaning.strip(), '排除':definition.excludes.strip(),
            '对象数量':definition.cardinality.value, '属性':props,
        })])
    sections.extend(['# 合同类别定义', '类别以核心义务交换和包含/排除边界确定，名称或别名只是线索。'])
    for entry in category_catalog.categories:
        definition = entry.definition
        item = {'code':definition.code, '别名':list(definition.aliases), '含义':definition.meaning,
                '核心义务交换':definition.core_exchange.model_dump(mode='json'),
                '包含':list(definition.includes), '排除':list(definition.excludes)}
        if definition.distinguish_from:
            item['相邻类别区分'] = [x.model_dump(mode='json') for x in definition.distinguish_from]
        sections.extend([f'## {definition.name}（{definition.code}）', block(item)])
    return '\n\n'.join(sections)
